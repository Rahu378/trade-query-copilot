-- One-time setup. Run as a role that can create databases and roles (e.g. SYSADMIN + SECURITYADMIN).
--   snow sql -f snowflake/01_setup.sql

CREATE WAREHOUSE IF NOT EXISTS COPILOT_WH
  WAREHOUSE_SIZE = XSMALL AUTO_SUSPEND = 60 AUTO_RESUME = TRUE INITIALLY_SUSPENDED = TRUE
  STATEMENT_TIMEOUT_IN_SECONDS = 60;

CREATE DATABASE IF NOT EXISTS TRADE_OPS;
CREATE SCHEMA IF NOT EXISTS TRADE_OPS.CORE;

CREATE STAGE IF NOT EXISTS TRADE_OPS.CORE.SEMANTIC_MODELS
  DIRECTORY = (ENABLE = TRUE)
  COMMENT = 'Cortex Analyst semantic model YAML';

CREATE FILE FORMAT IF NOT EXISTS TRADE_OPS.CORE.CSV_FMT
  TYPE = CSV SKIP_HEADER = 1 FIELD_OPTIONALLY_ENCLOSED_BY = '"' EMPTY_FIELD_AS_NULL = TRUE NULL_IF = ('');
CREATE STAGE IF NOT EXISTS TRADE_OPS.CORE.LOAD_STAGE FILE_FORMAT = TRADE_OPS.CORE.CSV_FMT;

-- The copilot runs as this role: read the tables, read the semantic model, call Cortex. Nothing else.
CREATE ROLE IF NOT EXISTS COPILOT_READER;
GRANT USAGE ON WAREHOUSE COPILOT_WH TO ROLE COPILOT_READER;
GRANT USAGE ON DATABASE TRADE_OPS TO ROLE COPILOT_READER;
GRANT USAGE ON SCHEMA TRADE_OPS.CORE TO ROLE COPILOT_READER;
GRANT SELECT ON ALL TABLES IN SCHEMA TRADE_OPS.CORE TO ROLE COPILOT_READER;
GRANT SELECT ON FUTURE TABLES IN SCHEMA TRADE_OPS.CORE TO ROLE COPILOT_READER;
GRANT READ ON STAGE TRADE_OPS.CORE.SEMANTIC_MODELS TO ROLE COPILOT_READER;
GRANT DATABASE ROLE SNOWFLAKE.CORTEX_USER TO ROLE COPILOT_READER;

