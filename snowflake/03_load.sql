USE SCHEMA TRADE_OPS.CORE;

PUT file://data/csv/*.csv @LOAD_STAGE AUTO_COMPRESS = TRUE OVERWRITE = TRUE;

COPY INTO DIM_ACCOUNT      FROM @LOAD_STAGE/dim_account.csv.gz      ON_ERROR = ABORT_STATEMENT;
COPY INTO DIM_COUNTERPARTY FROM @LOAD_STAGE/dim_counterparty.csv.gz ON_ERROR = ABORT_STATEMENT;
COPY INTO DIM_SECURITY     FROM @LOAD_STAGE/dim_security.csv.gz     ON_ERROR = ABORT_STATEMENT;
COPY INTO FX_RATES         FROM @LOAD_STAGE/fx_rates.csv.gz         ON_ERROR = ABORT_STATEMENT;
COPY INTO FACT_TRADES      FROM @LOAD_STAGE/fact_trades.csv.gz      ON_ERROR = ABORT_STATEMENT;
COPY INTO FACT_SETTLEMENTS FROM @LOAD_STAGE/fact_settlements.csv.gz ON_ERROR = ABORT_STATEMENT;
COPY INTO FACT_POSITIONS   FROM @LOAD_STAGE/fact_positions.csv.gz   ON_ERROR = ABORT_STATEMENT;
COPY INTO FACT_BREAKS      FROM @LOAD_STAGE/fact_breaks.csv.gz      ON_ERROR = ABORT_STATEMENT;

SELECT 'FACT_TRADES' t, COUNT(*) n FROM FACT_TRADES UNION ALL
SELECT 'FACT_SETTLEMENTS', COUNT(*) FROM FACT_SETTLEMENTS UNION ALL
SELECT 'FACT_POSITIONS', COUNT(*) FROM FACT_POSITIONS UNION ALL
SELECT 'FACT_BREAKS', COUNT(*) FROM FACT_BREAKS;
