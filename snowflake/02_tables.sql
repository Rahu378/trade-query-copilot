USE SCHEMA TRADE_OPS.CORE;

CREATE OR REPLACE TABLE DIM_ACCOUNT (
    ACCOUNT_ID       VARCHAR PRIMARY KEY,
    ACCOUNT_NAME     VARCHAR NOT NULL,
    DESK             VARCHAR NOT NULL,
    BASE_CURRENCY    VARCHAR(3) NOT NULL
);

CREATE OR REPLACE TABLE DIM_COUNTERPARTY (
    COUNTERPARTY_ID   VARCHAR PRIMARY KEY,
    COUNTERPARTY_NAME VARCHAR NOT NULL,
    LEI               VARCHAR(20),
    COUNTRY           VARCHAR(2),
    TIER              NUMBER(1)
);

CREATE OR REPLACE TABLE DIM_SECURITY (
    SECURITY_ID     NUMBER PRIMARY KEY,
    TICKER          VARCHAR NOT NULL,
    ISIN            VARCHAR(12),
    CUSIP           VARCHAR(9),
    SECURITY_NAME   VARCHAR,
    ASSET_CLASS     VARCHAR,
    CURRENCY        VARCHAR(3),
    SECTOR          VARCHAR,
    COUNTRY         VARCHAR(2)
);

CREATE OR REPLACE TABLE FX_RATES (
    RATE_DATE   DATE,
    CURRENCY    VARCHAR(3),
    USD_RATE    NUMBER(18, 8)
);

CREATE OR REPLACE TABLE FACT_TRADES (
    TRADE_ID         VARCHAR PRIMARY KEY,
    TRADE_DATE       DATE,
    SETTLE_DATE      DATE,
    ACCOUNT_ID       VARCHAR,
    SECURITY_ID      NUMBER,
    COUNTERPARTY_ID  VARCHAR,
    SIDE             VARCHAR(4),
    QUANTITY         NUMBER(38, 0),
    PRICE            NUMBER(18, 4),
    TRADE_CCY        VARCHAR(3),
    NOTIONAL_LOCAL   NUMBER(20, 2),
    NOTIONAL_USD     NUMBER(20, 2),
    TRADER           VARCHAR,
    TRADE_STATUS     VARCHAR
) CLUSTER BY (TRADE_DATE);

CREATE OR REPLACE TABLE FACT_SETTLEMENTS (
    TRADE_ID              VARCHAR PRIMARY KEY,
    EXPECTED_SETTLE_DATE  DATE,
    SETTLEMENT_STATUS     VARCHAR,
    ACTUAL_SETTLE_DATE    DATE,
    FAIL_REASON           VARCHAR,
    DAYS_FAILING          NUMBER
);

CREATE OR REPLACE TABLE FACT_POSITIONS (
    AS_OF_DATE                DATE,
    ACCOUNT_ID                VARCHAR,
    SECURITY_ID               NUMBER,
    TRADED_QUANTITY           NUMBER(38, 0),
    SETTLED_QUANTITY          NUMBER(38, 0),
    PRICE                     NUMBER(18, 4),
    CURRENCY                  VARCHAR(3),
    MARKET_VALUE_LOCAL        NUMBER(20, 2),
    MARKET_VALUE_USD          NUMBER(20, 2),
    SETTLED_MARKET_VALUE_USD  NUMBER(20, 2)
);

CREATE OR REPLACE TABLE FACT_BREAKS (
    BREAK_ID       VARCHAR PRIMARY KEY,
    OPENED_DATE    DATE,
    RESOLVED_DATE  DATE,
    ACCOUNT_ID     VARCHAR,
    SECURITY_ID    NUMBER,
    BREAK_TYPE     VARCHAR,
    BREAK_STATUS   VARCHAR,
    AMOUNT_USD     NUMBER(20, 2),
    AGE_DAYS       NUMBER,
    OWNER_TEAM     VARCHAR,
    ROOT_CAUSE     VARCHAR
);
